# بازی حدس عدد با ۳ تا شانس
import random
عدد_راز = random.randint(1, 5)
شانس = 3

while شانس > 0:
    حدس = int(input("عدد ۱ تا ۵ رو حدس بزن: "))
    if حدس == عدد_راز:
        print("بردی!")
        break
    else:
        شانس = شانس - 1
        print("غلط بود. شانس باقی مونده:", شانس)

if شانس == 0:
    print("باختی. عدد درست بود:", عدد_راز)
