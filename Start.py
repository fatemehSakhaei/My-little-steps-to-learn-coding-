# برنامه‌ای که از کاربر می‌پرسد چند تا درس امروز خوانده
# و بر اساس تعداد، نظر می‌دهد

درس‌ها = int(input("چند درس امروز خوندی؟ "))

if درس‌ها == 0:
    نظر = "امروز هیچی نخوندی! فقط یک کامیت کوچک بزن."
elif درس‌ها < 3:
    نظر = "خوبه، ولی بهتر از این می‌تونی."
else:
    نظر = "آفرین! برو یه کامیت سبز بزن."

print("نظر من:", نظر)
print("حالا بریم گیت‌هاب رو آپدیت کنیم.")
